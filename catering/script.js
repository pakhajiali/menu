// LANGUAGE SWITCHER LOGIC
// ============================================
let currentLang = 'en';

function getTranslation(key) {
    const t = translations[currentLang];
    return t && t[key] ? t[key] : key;
}

function updateStaticContent() {
    // Update all data-i18n elements
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.dataset.i18n;
        const translation = getTranslation(key);
        if (translation) {
            el.innerHTML = translation;
        }
    });

    // Update meta tags
    document.title = getTranslation('pageTitle');
    const metaDesc = document.querySelector('meta[name="description"]');
    if (metaDesc) metaDesc.content = getTranslation('metaDesc');
    const ogTitle = document.querySelector('meta[property="og:title"]');
    if (ogTitle) ogTitle.content = getTranslation('ogTitle');
    const ogDesc = document.querySelector('meta[property="og:description"]');
    if (ogDesc) ogDesc.content = getTranslation('ogDesc');
    const twitterTitle = document.querySelector('meta[name="twitter:title"]');
    if (twitterTitle) twitterTitle.content = getTranslation('twitterTitle');
    const twitterDesc = document.querySelector('meta[name="twitter:description"]');
    if (twitterDesc) twitterDesc.content = getTranslation('twitterDesc');

    // Update html lang attribute
    document.documentElement.lang = currentLang;
}

function setLanguage(lang) {
    currentLang = lang;
    localStorage.setItem('preferredLangCatering', lang);
    updateStaticContent();

    // Update active button
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.classList.toggle('active', btn.dataset.lang === lang);
    });
}

